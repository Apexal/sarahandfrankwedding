_INDEX: dict[str, tuple[frozenset[str], ...]] = {}
for _group in _GROUPS:
    _members = frozenset(_group)
    for _name in _members:
        _INDEX[_name] = (*_INDEX.get(_name, ()), _members)


def are_nicknames(first: str, second: str) -> bool:
    """True when the two (normalized) names share a nickname group and differ from each other."""
    if not first or not second or first == second:
        return False
    return any(second in group for group in _INDEX.get(first, ()))


def nicknames_for(name: str) -> frozenset[str]:
    """Every name interchangeable with `name`, not including itself."""
    equivalents: set[str] = set()
    for group in _INDEX.get(name, ()):
        equivalents.update(group)
    equivalents.discard(name)
    return frozenset(equivalents)
